function translateDom() {
  const language =
    localStorage.getItem("nova_language") || "en";

  if (language !== "hi") {
    return;
  }

  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT
  );

  const nodes = [];
  let node;

  while ((node = walker.nextNode())) {
    nodes.push(node);
  }

  for (const textNode of nodes) {
    const parent = textNode.parentElement;

    if (!parent) {
      continue;
    }

    const original = textNode.nodeValue;
    const trimmed = original.trim();

    if (!trimmed) {
      continue;
    }

    if (
      parent.closest(
        "script, style, textarea, code, pre"
      )
    ) {
      continue;
    }

    const translated =
      HI_TRANSLATIONS[trimmed];

    if (
      translated &&
      translated !== trimmed
    ) {
      textNode.nodeValue =
        original.replace(
          trimmed,
          translated
        );
    }
  }

  const elements =
    document.querySelectorAll(
      "input[placeholder], textarea[placeholder], button[aria-label], input[aria-label], textarea[aria-label]"
    );

  for (const element of elements) {
    for (const attr of [
      "placeholder",
      "aria-label",
    ]) {
      const value =
        element.getAttribute(attr);

      if (!value) {
        continue;
      }

      const translated =
        HI_TRANSLATIONS[value];

      if (translated) {
        element.setAttribute(
          attr,
          translated
        );
      }
    }
  }
}

export function initializeNovaLocalization() {
  if (
    typeof window === "undefined"
  ) {
    return () => {};
  }

  translateDom();

  const observer =
    new MutationObserver(() => {
      translateDom();
    });

  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
  });

  const interval =
    window.setInterval(() => {
      translateDom();
    }, 700);

  return () => {
    observer.disconnect();
    window.clearInterval(interval);
  };
}